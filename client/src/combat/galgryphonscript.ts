// The Gal Gryphon's pattern script (PsoBB.exe, Ephinea 1.25.13): how the state
// the Gryphon moves into is chosen, and the record that carries it to the other
// clients. Addresses are VAs; "dump N" is a line of
// reverse/refsrc/original-psobb-client-source/src/Psobb.exe-05112026.c.
//
// Who chooses. update_gal_gryphon (dump 226140) splits on the follower flag
// (+0x4e8, set in galgryphon_constructor, dump 225773, from the party-leader check):
// a follower only plays the state its 0xA0 sync gives it (SyncPlayerToEntityTransform_004a7034,
// dump 226104). The leader makes the choice itself. The packet it sends goes out
// through checked_call_packet0x60_subcommand (dump 815078), which also runs the 0xA0
// handler on the sender, so the leader's own state is set from the same record. Hence
// the choice is local to the leader (RNG + table), and the network only carries it.
//
// Where the choice is made. Two walkers share the table and the ops:
//  - the default list (ProcessGalgryphonDefaultSubcommandPacket_004a8d5c, dump 227369),
//    run by the entry state S4 (GalgryphonUpdateState_004a22b0, dump 224151) once its
//    entry motion ends (+0xb0 & 0x10 sets +0x6e4 = 1), from the table's first list (+0x00);
//  - the stage lists (ProcessGalgryphonSubcommandPacket_004a7390, dump 226277), run from
//    HandleGalgryphonState9_004a7360 (dump 226240) only when the flags allow it and the
//    current HP is <= 0: a death script (see galgryphonStageDue).
// Both call the same selection (SelectGalgryphonRandomState_004a771c, dump 226437),
// roll (CalculateGalgryphonRandomPacketValue_004a8c9c, dump 227308) and op handler.
//
// The walk keeps its cursor between packets (+0x77c). A branch record (op 0x21) picks
// the next list by a table offset; any other record yields one packet (the state is its
// op, the duration is its roll) and the cursor moves on; a hold record (op 0x22) yields
// its packet and does not move. The death lists end in a hold, so the packet with op 34
// (S34, the remove state) ends the death script.
//
// Data: galgryphonscriptdata.ts (generated by tools/gen-galgryphon-script.py from the
// exe). Not ported here: the state handlers the packets start (docs/bosses/
// galgryphon-states-a.md and -b.md), which are the Gryphon brain itself.

import { GALGRYPHON_SCRIPT_SLOTS, type GalgryphonScriptRecord } from './galgryphonscriptdata.ts';

export const GALGRYPHON_OP = {
  // 0x21 (33) is a branch; the seed record of the state list also carries 0x21 (S33).
  branch: 0x21,
  // 0x22 (34) is a hold: the cursor stays, the packet is still sent (state 34 = remove).
  hold: 0x22,
} as const;

// Table byte offsets (the pointer table 0x009ab820, slot k at 4k) the walker starts from.
export const GALGRYPHON_LIST = {
  // +0x00: the default list (ProcessGalgryphonDefaultSubcommandPacket_004a8d5c, `**(this+0x780)`).
  default: 0x00,
  // The stage lists (ProcessGalgryphonSubcommandPacket_004a7390's stage entry, PROVEN):
  // stage 1 -> +0x68, 3 -> +0x6c, 2 -> +0x70, any other stage -> +0x64.
  stage1: 0x68,
  stage3: 0x6c,
  stage2: 0x70,
  stageOther: 0x64,
} as const;

export type GalgryphonStage = 1 | 2 | 3 | 'other';

export function galgryphonStageList(stage: GalgryphonStage): number {
  if (stage === 1) return GALGRYPHON_LIST.stage1;
  if (stage === 3) return GALGRYPHON_LIST.stage3;
  if (stage === 2) return GALGRYPHON_LIST.stage2;
  return GALGRYPHON_LIST.stageOther;
}

// The probability constants (tools/exedata.py, PROVEN): 0.9 at 0x00903ba4, 0.8 at 0x00903ba8,
// 0.4 at 0x00903bac, 0.3 at 0x00903bb0, 0.6 at 0x00903bb4, 0.2 at 0x00903bb8; rand() is
// divided by 32768 (0x00903bbc). The two tables are indexed by P (clamped to 0..7).
export const GALGRYPHON_PROB = {
  t09: 0.9,
  t08: 0.8,
  t04: 0.4,
  t03: 0.3,
  t06: 0.6,
  t02: 0.2,
  // T924[P] at 0x00903924: the branch 1 / 2 threshold per P.
  bySpeed: [0, 0, 0, 0, 0.2, 0.3, 0.4, 0.5],
  // T900[P] at 0x00903900: the branch 1 HP threshold per P.
  byHp: [0, 0, 0.1, 0.2, 0.2, 0.3, 0.4, 0.4],
} as const;

// The ops that have a handler (the others only take their roll; dump 226437's op table
// 0x009a7f58, PROVEN from docs/bosses/galgryphon-script.md section 3.4).
const OP_08 = 0x08;
const OP_09 = 0x09;
const OP_0A = 0x0a;
const OP_0E = 0x0e;
const OP_1B = 0x1b;
const OP_1E = 0x1e;

export interface GalgryphonScriptContext {
  // A value in [0, 1): the exe's rand() / 32768.
  rand: () => number;
  // P: the party size the branches use (ASSUMED: the exe reads it from the animation
  // speed entry 2, field 0x28; the docs call it DAT_00a47640+0x28). Clamped to 0..7.
  players: number;
  // Current HP over max HP (branch type 1 only). The exe reads both shorts (+0x334 / +0x2bc).
  hpRatio: number;
  // The entity's heading in radians (the op 0x0a speed vector; ASSUMED: the exe's
  // fpatan of the heading from the position).
  heading: number;
}

// One resolved packet: the 0x14-byte record the 0xA0 sync carries (the record layout of
// galgryphon-script.md section 1.2). `op` is the state; `roll` the duration in ticks
// (-1 never expires); a..d the handler's values (+4, +8, +0xc, +0x10). Floats are kept as
// numbers; the exe stores some of them as bit patterns (the receiver only reads op and roll).
export interface GalgryphonPacket {
  op: number;
  roll: number;
  a: number;
  b: number;
  c: number;
  d: number;
}

// ROUND in the exe (round half up for the positive values used here).
function round(x: number): number {
  return Math.floor(x + 0.5);
}

function clampP(p: number): number {
  return Math.max(0, Math.min(7, Math.trunc(p)));
}

function slotIndex(offset: number): number {
  return offset / 4;
}

// The walker. One instance per Gryphon; its cursor and the 0x200 bit of +0x4c8 (the
// "branch 1 rolled" flag, ASSUMED meaning) live here.
export class GalgryphonScript {
  private list = -1; // slot index of the current record's list; -1 = no cursor
  private index = 0; // record index inside that list
  private bit200 = false;

  /** The cursor is on a list (it was restarted and no hold ended the walk). */
  get started(): boolean {
    return this.list >= 0;
  }

  /** The 0x200 flag of +0x4c8 (branch type 1's "rolled this step"). */
  get flag200(): boolean {
    return this.bit200;
  }

  /** Point the cursor at the first record of the list at table offset `offset`. */
  restart(offset: number): void {
    const slot = slotIndex(offset);
    if (slot < 0 || slot >= GALGRYPHON_SCRIPT_SLOTS.length) throw new Error(`galgryphon: no list at +${offset.toString(16)}`);
    this.list = slot;
    this.index = 0;
  }

  /**
   * One packet: follow the branches from the cursor, roll and resolve the record there,
   * and move the cursor (not past a hold). Returns `held` when the record was a hold.
   */
  next(ctx: GalgryphonScriptContext): { packet: GalgryphonPacket; held: boolean } {
    if (this.list < 0) throw new Error('galgryphon: next() before restart()');
    for (let guard = 0; guard < 1024; guard++) {
      const rec: GalgryphonScriptRecord | undefined = GALGRYPHON_SCRIPT_SLOTS[this.list]?.[this.index];
      if (!rec) throw new Error(`galgryphon: cursor past the list ${this.list}`);
      if (rec.op === GALGRYPHON_OP.branch) {
        this.list = slotIndex(this.branch(rec.i8, ctx));
        this.index = 0;
        continue;
      }
      const packet = this.resolve(rec, ctx);
      if (rec.op !== GALGRYPHON_OP.hold) this.index++;
      return { packet, held: rec.op === GALGRYPHON_OP.hold };
    }
    throw new Error('galgryphon: branches did not reach a record');
  }

  /**
   * SelectGalgryphonRandomState_004a771c (dump 226437): the table offset the branch
   * type picks. The draws are taken in the exe's order.
   */
  branch(type: number, ctx: GalgryphonScriptContext): number {
    const P = clampP(ctx.players);
    const PR = GALGRYPHON_PROB;
    if (type === 0) {
      const r = ctx.rand();
      if (r < PR.t06) return 0x08;
      if (PR.t09 <= r) return 0x10;
      return 0x0c;
    }
    if (type === 1) {
      if (this.bit200 && P > 4) {
        this.bit200 = false;
        return 0x24;
      }
      this.bit200 = true;
      if (ctx.rand() < PR.bySpeed[P]) return 0x24;
      const hp = ctx.hpRatio;
      if (ctx.rand() < PR.byHp[P]) return hp <= ctx.rand() ? 0x20 : 0x1c;
      return hp <= ctx.rand() ? 0x18 : 0x14;
    }
    if (type === 2) {
      const r = ctx.rand();
      return PR.bySpeed[P] <= r ? 0x28 : 0x24;
    }
    if (type === 3) {
      const r = ctx.rand();
      if (r < PR.t03) return 0x2c;
      if (r < PR.t04) return 0x30;
      if (r < PR.t06) return 0x34;
      if (r < PR.t08) return 0x38;
      return 0x3c;
    }
    if (type === 4) {
      const r = ctx.rand();
      if (r < PR.t02) return P < 2 ? 0x40 : 0x4c;
      if (r < PR.t06) return P < 4 ? 0x44 : 0x50;
      return P > 5 ? 0x54 : 0x48;
    }
    if (type === 5) return 0x58;
    if (type === 6) return 0x10;
    throw new Error(`galgryphon: branch type ${type} has no rule`);
  }

  /**
   * CalculateGalgryphonRandomPacketValue_004a8c9c (dump 227308) and the op handler
   * (table 0x009a7f58). The roll is always drawn; a handler adds its own draws.
   */
  resolve(rec: GalgryphonScriptRecord, ctx: GalgryphonScriptContext): GalgryphonPacket {
    const r = ctx.rand;
    const out: GalgryphonPacket = { op: rec.op, roll: 0, a: 0, b: 0, c: 0, d: 0 };
    out.roll = round(r() * rec.range + rec.min);
    switch (rec.op) {
      case OP_08:
        // ASSUMED: +4 (helpers 0x4a6250 / 0x4a62b4, UNCLEAR) is left 0.
        out.b = rec.f28 + r() * rec.f2c;
        break;
      case OP_09: {
        out.a = round(rec.i10 + r() * rec.i14);
        out.c = rec.f28 + r() * rec.f2c;
        out.d = rec.f30 + r() * rec.f34;
        out.b = rec.i8 >= 1 ? 1 : rec.i8 < 0 ? -1 : r() >= 0.5 ? 1 : -1;
        break;
      }
      case OP_0A: {
        const t = round(rec.i8 + r() * rec.i0c);
        if (t === 0) {
          const speed = rec.f30 + r() * rec.f34;
          out.a = speed * Math.cos(ctx.heading);
          out.b = speed * Math.sin(ctx.heading);
        } else if (t === 1) {
          out.a = rec.f30 + r() * rec.f34;
          out.b = rec.f38 + r() * rec.f3c;
        }
        out.c = rec.f28 + r() * rec.f2c;
        out.d = round(rec.i10 + r() * rec.i14);
        break;
      }
      case OP_0E: {
        // ASSUMED: +4 (f(rec,1) * f(rec,0), UNCLEAR) is left 0.
        out.b = rec.f28 + r() * rec.f2c;
        const v = rec.f30 + r() * rec.f34;
        out.c = v * v;
        break;
      }
      case OP_1B:
      case OP_1E:
        // ROUND(rand / 32768 * 2^32): a random 32-bit value (ASSUMED: a BAMS heading).
        out.a = Math.min(0xffffffff, round(r() * 4294967296));
        break;
      default:
        break;
    }
    return out;
  }
}

/**
 * The death script is due (HandleGalgryphonState9_004a7360, dump 226240): the flags of
 * +0x4c8 have neither 0x4 nor 0x8 (0x8 is set by the first run and never cleared in the
 * dump, so the script runs once) and the current HP is <= 0 (PROVEN from `jle` at
 * 0x004a7388). With HP above 0 the call is the phase-9 dispatch instead.
 */
export function galgryphonStageDue(flags: number, hpCurrent: number): boolean {
  return (flags & 0xc) === 0 && hpCurrent <= 0;
}

/**
 * The 0xA0 sync a follower receives (SyncPlayerToEntityTransform_004a7034, dump 226104):
 * u16 entity id @2, float position @4/8/c, u32 heading @0x10, then the 0x14 record at 0x14
 * (state short @0x14, duration short @0x16, then four words). The state is the record's
 * op; the sender's loop-back uses the same bytes. Returns null for a short buffer.
 */
export interface GalgryphonSync {
  entityId: number;
  x: number;
  y: number;
  z: number;
  heading: number;
  state: number;
  duration: number;
  a: number;
  b: number;
  c: number;
  d: number;
}

export function decodeGalgryphonSync(view: DataView): GalgryphonSync | null {
  if (view.byteLength < 0x28) return null;
  return {
    entityId: view.getUint16(2, true),
    x: view.getFloat32(4, true),
    y: view.getFloat32(8, true),
    z: view.getFloat32(0xc, true),
    heading: view.getUint32(0x10, true),
    state: view.getUint16(0x14, true),
    duration: view.getInt16(0x16, true),
    a: view.getInt32(0x18, true),
    b: view.getInt32(0x1c, true),
    c: view.getInt32(0x20, true),
    d: view.getInt32(0x24, true),
  };
}
