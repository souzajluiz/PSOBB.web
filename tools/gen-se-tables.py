#!/usr/bin/env python3
# Generates client/src/audio/se_tables.ts from PsoBB.exe (Ephinea build,
# image base 0x400000): the sound effect id/slot/bank tables used by the
# SE player (FUN_00814298 -> FUN_00828e4c) and the bank loaders
# (FUN_00829a04 for common.pac, FUN_00828d40 for the area bank).
#
# Usage: python3 tools/gen-se-tables.py /path/to/PsoBB.exe > client/src/audio/se_tables.ts
#
# Tables read (virtual addresses):
#   0x00a1f840  i32[0x700]  SE id -> wave slot (FUN_0081443c; mostly identity)
#   0x00a13b20  u32[0x700]  per-slot flags (FUN_008290f4):
#                 bits 8..14  attenuation 0..127 (FUN_00814298 volume)
#                 bit 15      3D buffer when the type nibble is 0 (FUN_00829130)
#                 bits 24..27 buffer type (0 / 10 = 3D)
#                 bit 28      several voices of the slot may overlap (FUN_00829c38)
#                 bit 31      random pitch offset (stored at voice +0x34, unused
#                             on PC: the buffers lack DSBCAPS_CTRLFREQUENCY)
#   0x00a21560  char*[26]   bank file names ("ancient.pac" ...)
#   0x00a214e0  u32[26]     entries per bank
#   0x00a21460  i32*[26]    wave slot of each bank entry
#   0x00a215e0  rec*[26]    16-byte entry records:
#                 +0 u8 group, +1 u8 index, +2 u8 flags (bit 0 = loop),
#                 +4 u32 file offset, +8 u32 loop start, +0xc u32 loop end
#                 (samples; the loop runs loop start .. end of the wave, see
#                 FUN_00828978)
#   0x00989e60  i32[]       area -> bank (FUN_00828d40)
#
# The file offsets are not emitted: the entries are stored in table order, each
# padded to 32 bytes, so the client walks the file (checked in tests/sound.test.ts).
import struct
import sys

exe = open(sys.argv[1], 'rb').read()
pe = struct.unpack_from('<I', exe, 0x3C)[0]
nsec = struct.unpack_from('<H', exe, pe + 6)[0]
optsize = struct.unpack_from('<H', exe, pe + 20)[0]
sections = []
for i in range(nsec):
    o = pe + 24 + optsize + i * 40
    vsize, va, rsize, raw = struct.unpack_from('<IIII', exe, o + 8)
    sections.append((va + 0x400000, vsize, raw, rsize))


def off(va):
    for base, vsize, raw, rsize in sections:
        if base <= va < base + max(vsize, rsize):
            return raw + va - base
    raise ValueError(hex(va))


def u32(va):
    return struct.unpack_from('<I', exe, off(va))[0]


def i32(va):
    return struct.unpack_from('<i', exe, off(va))[0]


def cstr(va):
    o = off(va)
    return exe[o:exe.index(b'\0', o)].decode('latin1')


NBANK = 26
NAREA = 49
banks = []
used = set()
for b in range(NBANK):
    name = cstr(u32(0xA21560 + 4 * b))
    n = u32(0xA214E0 + 4 * b)
    sl = u32(0xA21460 + 4 * b)
    rec = u32(0xA215E0 + 4 * b)
    slots = [i32(sl + 4 * k) for k in range(n)]
    loops = []
    prev = -1
    for k in range(n):
        e = rec + 16 * k
        o = u32(e + 4)
        assert o > prev
        prev = o
        if exe[off(e + 2)] & 1:
            loops.append((k, u32(e + 8), u32(e + 12)))
    used.update(slots)
    banks.append((name, slots, loops))

remap = [(i, i32(0xA1F840 + 4 * i)) for i in range(0x700) if i32(0xA1F840 + 4 * i) != i]
for _, s in remap:
    used.add(s)
flags = [(s, u32(0xA13B20 + 4 * s)) for s in sorted(used) if 0 <= s < 0x700]
areas = [i32(0x989E60 + 4 * i) for i in range(NAREA)]

out = []
w = out.append
w('// Generated by tools/gen-se-tables.py from PsoBB.exe. Do not edit.')
w('// Addresses and field meanings: see the generator and docs/PROTOCOL.md "Sound effects".')
w('')
w('export interface SeBankTable {')
w('  file: string;')
w('  /** Wave slot of each entry, in file order (0x00a21460). */')
w('  slots: number[];')
w('  /** [entry, loop start, loop end] in samples, for entries with the loop flag. */')
w('  loops: [number, number, number][];')
w('}')
w('')
w('/** Banks in the order of the name table 0x00a21560. */')
w('export const SE_BANKS: SeBankTable[] = [')
for name, slots, loops in banks:
    w(f"  {{ file: '{name}', slots: [{', '.join(hex(s) for s in slots)}], loops: [{', '.join(f'[{k}, {a}, {b}]' for k, a, b in loops)}] }},")
w('];')
w('')
w('/** Area -> bank index (0x00989e60), used by FUN_00828d40. */')
w(f'export const SE_AREA_BANK = [{", ".join(str(a) for a in areas)}];')
w('')
w('/** SE ids whose slot differs from the id (0x00a1f840). */')
w('export const SE_ID_REMAP: Record<number, number> = {')
for i in range(0, len(remap), 8):
    w('  ' + ' '.join(f'{hex(a)}: {hex(b)},' for a, b in remap[i:i + 8]))
w('};')
w('')
w('/** Flags of every slot a bank or the remap uses (0x00a13b20). */')
w('export const SE_SLOT_FLAGS: Record<number, number> = {')
for i in range(0, len(flags), 6):
    w('  ' + ' '.join(f'{hex(a)}: 0x{b:08x},' for a, b in flags[i:i + 6]))
w('};')
print('\n'.join(out))
