#!/usr/bin/env python3
# Generates client/src/render/playertables.ts from PsoBB.exe (Ephinea build,
# image base 0x400000): the per-class player appearance records and the
# texture name tables the client uses to build a player's texture lists.
#
# Usage: python3 tools/gen-player-tables.py /path/to/PsoBB.exe > client/src/render/playertables.ts
#
# Tables read (addresses are virtual addresses in PsoBB.exe):
#   0x009b5b60  12 x 0x2c appearance records, one per class (the model name
#               lists are read with max(limit, 1) entries; a null cap = no cap):
#               +0x00 i16 limits[5]: costume, skin, face, head, hair (count,
#                     0 = field must be 0); checked by FUN_004e665c
#               +0x10 char** hair model names [hair]   (plXhaiNN.nj)
#               +0x14 char** cap model names [hair]    (plXcapNN.nj or NULL)
#               +0x18 char** head model names [head]   (plXhedNN.nj)
#               +0x1c char*  body model name           (plXbdy00.nj)
#               +0x20 TEXLIST*[hair] hair texture name lists (hai + cap)
#               +0x24 TEXLIST*[head] head texture name lists
#               +0x28 TEXLIST*        body texture name list
#               (TEXLIST = { char** names, u32 count })
#   0x009b59e0  23 x 0x10 texture archives: { u32 file id, u32 count,
#               char* "PLXTEX.AFS", char** names }; names[i] is the name of
#               entry i of plXtex.afs, sorted (FUN_004ed735 binary-searches it).
#   0x009b8e40  i32[23] plZsmpnj.afs entries per proportion target (heads + body)
#   0x009b8ea0  i32[23] first plZsmpnj.afs entry of each class
import struct
import sys

exe = open(sys.argv[1], 'rb').read()
pe = struct.unpack_from('<I', exe, 0x3C)[0]
nsec = struct.unpack_from('<H', exe, pe + 6)[0]
optsize = struct.unpack_from('<H', exe, pe + 20)[0]
sections = []
for i in range(nsec):
    o = pe + 24 + optsize + i * 40
    vsize, va, rsize, raw = struct.unpack_from('<IIII', exe, o + 8)
    sections.append((va + 0x400000, vsize, raw, rsize))


def off(va):
    for base, vsize, raw, rsize in sections:
        if base <= va < base + min(vsize, rsize):
            return raw + va - base
    raise ValueError(hex(va))


def u32(va): return struct.unpack_from('<I', exe, off(va))[0]
def i32(va): return struct.unpack_from('<i', exe, off(va))[0]
def i16(va): return struct.unpack_from('<h', exe, off(va))[0]


def cstr(va):
    o = off(va)
    return exe[o:exe.index(b'\0', o)].decode('ascii')


def texlist(p):
    names, n = u32(p), u32(p + 4)
    return [cstr(u32(names + 4 * i)) for i in range(n)]


out = []
for c in range(12):
    rec = 0x9B5B60 + 0x2C * c
    limits = [i16(rec + 2 * i) for i in range(5)]
    hair_t, head_t, body_t = u32(rec + 0x20), u32(rec + 0x24), u32(rec + 0x28)
    arc = 0x9B59E0 + 0x10 * c
    names = [cstr(u32(u32(arc + 12) + 4 * i)) for i in range(u32(arc + 4))]
    index = {n: i for i, n in enumerate(names)}
    lists = lambda ls: [[index[n] for n in l] for l in ls]
    # Part model names: plXhaiNN.nj (hair), plXcapNN.nj (cap, None when the
    # exe's pointer is NULL) and plXhedNN.nj (head), by index.
    def modellist(p, count, nullable=False):
        if not p:
            return None
        out_ = []
        for i in range(max(count, 1)):
            q = u32(p + 4 * i)
            out_.append(cstr(q) if q else None)
        return out_ if nullable else [x for x in out_ if x is not None]
    models = {
        'hair': modellist(u32(rec + 0x10), limits[4]),
        'cap': modellist(u32(rec + 0x14), limits[4], True),
        'head': modellist(u32(rec + 0x18), limits[3]) or [],
    }
    out.append({
        'limits': limits,
        'body': [index[n] for n in texlist(body_t)],
        'head': lists(texlist(u32(head_t + 4 * i)) for i in range(max(limits[3], 1))),
        'hair': lists(texlist(u32(hair_t + 4 * i)) for i in range(max(limits[4], 1))) if hair_t else None,
        'names': names,
        'models': models,
        'addr': (rec, body_t, head_t, hair_t, u32(arc + 12)),
    })

smp_count = [i32(0x9B8E40 + 4 * c) for c in range(12)]
smp_base = [i32(0x9B8EA0 + 4 * c) for c in range(12)]

p = print
p('// Generated by tools/gen-player-tables.py from PsoBB.exe; do not edit.')
p('// Per class: the appearance limits and texture name lists of the appearance')
p('// record at 0x009b5b60 + 0x2c * class, and the entry names of pl<L>tex.afs')
p('// (0x009b59e0 + 0x10 * class). Texture lists hold indices into `names`;')
p('// the name of entry i of pl<L>tex.afs is "pxt" + names[i].')
p()
p('export interface PlayerClassTables {')
p('  // Number of costumes, skins, faces, heads, hair styles (0: the field must be 0).')
p('  limits: readonly [number, number, number, number, number];')
p('  body: readonly number[];')
p('  head: readonly (readonly number[])[]; // per head')
p('  hair: readonly (readonly number[])[] | null; // per hair style (hai + cap)')
p('  // Part model names by index: hair (plXhaiNN.nj), cap (plXcapNN.nj, null = no cap\n  // for that style), head (plXhedNN.nj).')
p('  models: { hair: readonly string[] | null; cap: readonly (string | null)[] | null; head: readonly string[] };')
p('  names: readonly string[];')
p('}')
p()
p('const n = (s: string): string[] => s.split(\' \');')
p()
p('export const PLAYER_CLASS_TABLES: readonly PlayerClassTables[] = [')
for c, o in enumerate(out):
    rec, body_t, head_t, hair_t, names_p = o['addr']
    p(f'  // class {c}: record 0x{rec:08x}, body list 0x{body_t:08x}, head lists 0x{head_t:08x}, ' +
      (f'hair lists 0x{hair_t:08x}, ' if hair_t else '') + f'names 0x{names_p:08x}')
    p('  {')
    p(f'    limits: [{", ".join(map(str, o["limits"]))}],')
    p(f'    body: [{", ".join(map(str, o["body"]))}],')
    p(f'    head: [{", ".join("[" + ", ".join(map(str, l)) + "]" for l in o["head"])}],')
    if o['hair'] is None:
        p('    hair: null,')
    else:
        p(f'    hair: [{", ".join("[" + ", ".join(map(str, l)) + "]" for l in o["hair"])}],')
    m = o['models']
    j = lambda v: 'null' if v is None else '[' + ', '.join('null' if x is None else repr(x).replace("'", '"') for x in v) + ']'
    p(f'    models: {{ hair: {j(m["hair"])}, cap: {j(m["cap"])}, head: {j(m["head"])} }},')
    p(f'    names: n(\'{" ".join(s[3:] for s in o["names"])}\'),')
    p('  },')
p('];')
p()
p('// plZsmpnj.afs layout (0x009b8e40, 0x009b8ea0): class c, proportion target t')
p('// (0..6), part k: entry SMP_BASE[c] + SMP_COUNT[c] * t + k; k = head index for')
p('// the head, k = SMP_COUNT[c] - 1 for the body.')
p(f'export const SMP_COUNT: readonly number[] = [{", ".join(map(str, smp_count))}];')
p(f'export const SMP_BASE: readonly number[] = [{", ".join(map(str, smp_base))}];')
