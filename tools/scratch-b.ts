import { readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { BBSession } from '../client/src/net/bbsession.ts';
import { Game } from '../client/src/net/game.ts';
import { GameItems } from '../client/src/net/items.ts';
import { nodeBridge } from '../tests/lib/nodews.ts';
const ROOT = resolve(import.meta.dirname, '..');
const nsk = new Uint8Array(readFileSync(join(ROOT, 'vendor/newserv/system/blueburst/keys/default.nsk')));
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
const session = new BBSession({ nsk, connect: nodeBridge });
await session.login('webitemb', 'webitemb');
await session.characterPreviews();
const lobby = await session.enterLobby('webitemb', 'webitemb', 0);
const entry = (await Game.list(lobby.conn)).find((g) => g.name.startsWith('ItemHunter'))!;
const g = await Game.join(lobby, { guildCardNumber: session.init!.guildCardNumber, fullCharacter: () => session.fullCharacter }, entry.itemId);
const items = new GameItems(g, { character: () => session.character, fullCharacter: () => session.fullCharacter });
await sleep(1000);
g.finishLoading(0, 0, 0, 0);
items.ensureIds();
console.log('B sees floor items (6x6D):', [...items.floorItems.values()].map((i) => `${i.id.toString(16)} ${[...i.data.data1.slice(0, 6)].join(',')} @${i.x.toFixed(0)},${i.z.toFixed(0)}`));
const a = g.players.get(0)!;
console.log('A at', a.position);
g.sendStop(a.position.x + 20, a.position.y, a.position.z, 0);
await sleep(300);
const mate = session.character!.inventory.find((i) => i.data.data1[0] === 3 && i.data.data1[1] === 0)!;
items.drop(mate.data.id, 1);
console.log('B dropped one monomate at', a.position.x + 20, a.position.z);
items.onFloorItemRemoved = (i) => console.log('B saw pickup of', i.id.toString(16));
await sleep(Number(process.argv[2] ?? 25000));
await g.leave();
session.close();
process.exit(0);
