#!/usr/bin/env python3
# Generates client/src/combat/galgryphonscriptdata.ts from PsoBB.exe: the Gal
# Gryphon (TBoss5Gryphon, Ep2) pattern script that the leader's state choice
# walks (docs/bosses/galgryphon-script.md sections 1.2, 2.2, 3).
#
# Usage: python3 tools/gen-galgryphon-script.py > client/src/combat/galgryphonscriptdata.ts
#        python3 tools/gen-galgryphon-script.py --dump   (per-slot listing, for review)
#
# Reads (virtual addresses; PSOBB_EXE or ~/Downloads/psobb-client/PsoBB.exe):
#   0x009ab820  pointer table g_pGalgryphonNullVtable: 29 slots, 4 bytes each.
#               Slot k (byte offset 4k) is the address of the first 0x48-byte record
#               of that pattern list (the ctor sets this+0x780 to this table).
#   record (0x48 bytes): u32 op @0, i16 min @4, i16 range @6, i32 @8 (branch type /
#               0x0a selector / 0x09 sign), i32 @0xc, i32 @0x10 (min), i32 @0x14
#               (range), float @0x28 / @0x2c, @0x30 / @0x34, @0x38 / @0x3c, @0x40.
#
# A list runs from its first record through the first record whose op is 0x21
# (branch) or 0x22 (hold): both are kept, the walker never reads past them. The
# branch's targets are other slot numbers (byte offsets into the pointer table),
# which the walker resolves at run time (galgryphonscript.ts).
import struct
import os
import sys

PATH = os.environ.get("PSOBB_EXE", os.path.expanduser("~/Downloads/psobb-client/PsoBB.exe"))
TABLE = 0x009AB820
SLOTS = 29
RECORD = 0x48
BRANCH = 0x21
HOLD = 0x22

DATA = open(PATH, "rb").read()
_pe = struct.unpack_from("<I", DATA, 0x3C)[0]
_nsect, = struct.unpack_from("<H", DATA, _pe + 6)
_optsize, = struct.unpack_from("<H", DATA, _pe + 20)
BASE, = struct.unpack_from("<I", DATA, _pe + 24 + 28)
SECTIONS = []
for i in range(_nsect):
    o = _pe + 24 + _optsize + i * 40
    name = DATA[o : o + 8].rstrip(b"\0").decode("ascii", "replace")
    vsize, va, rawsize, raw = struct.unpack_from("<IIII", DATA, o + 8)
    SECTIONS.append((name, BASE + va, max(vsize, rawsize), raw, rawsize))


def offset(va):
    for _, start, size, raw, rawsize in SECTIONS:
        if start <= va < start + size:
            if va - start >= rawsize:
                return None
            return raw + (va - start)
    return None


def read(va, n):
    o = offset(va)
    if o is None:
        raise SystemExit(f"{va:#010x}: not in an initialised section")
    return DATA[o : o + n]


def record(va):
    b = read(va, RECORD)
    op = struct.unpack_from("<I", b, 0)[0]
    mn = struct.unpack_from("<h", b, 4)[0]
    rg = struct.unpack_from("<h", b, 6)[0]
    t8 = struct.unpack_from("<i", b, 8)[0]
    t0c = struct.unpack_from("<i", b, 0xC)[0]
    t10 = struct.unpack_from("<i", b, 0x10)[0]
    t14 = struct.unpack_from("<i", b, 0x14)[0]
    f = {k: struct.unpack_from("<f", b, k)[0] for k in (0x28, 0x2C, 0x30, 0x34, 0x38, 0x3C, 0x40)}
    return {
        "op": op, "min": mn, "range": rg, "i8": t8, "i0c": t0c, "i10": t10, "i14": t14,
        "f28": f[0x28], "f2c": f[0x2C], "f30": f[0x30], "f34": f[0x34],
        "f38": f[0x38], "f3c": f[0x3C], "f40": f[0x40],
    }


def slot_list(k):
    """The records of slot k, from its first record through the branch or hold."""
    va = struct.unpack_from("<I", read(TABLE + 4 * k, 4), 0)[0]
    out = []
    while True:
        r = record(va)
        out.append(r)
        if r["op"] in (BRANCH, HOLD):
            return out
        va += RECORD
        if len(out) > 64:
            raise SystemExit(f"slot {k}: no branch or hold within 64 records")


def fmt(v):
    if isinstance(v, float):
        return f"{v:.9g}" if "." in f"{v:.9g}" or "e" in f"{v:.9g}" else f"{v:.9g}.0"
    return str(v)


def main():
    slots = [slot_list(k) for k in range(SLOTS)]
    if "--dump" in sys.argv:
        for k, recs in enumerate(slots):
            ops = " ".join(f"{r['op']:02x}" for r in recs)
            print(f"slot +{4 * k:02x} ({len(recs)}): {ops}")
            for r in recs:
                print("   ", {kk: vv for kk, vv in r.items()})
        print("total records", sum(len(s) for s in slots))
        return
    total = sum(len(s) for s in slots)
    print("// GENERATED by tools/gen-galgryphon-script.py from PsoBB.exe (table 0x009ab820,")
    print("// records 0x48 bytes). Do not edit by hand. The op numbers are the exe's; a branch")
    print("// (0x21) and a hold (0x22) end their list. " + f"{total} records in {SLOTS} lists.")
    print("")
    print("export interface GalgryphonScriptRecord {")
    print("  op: number;")
    print("  min: number;")
    print("  range: number;")
    print("  i8: number;")
    print("  i0c: number;")
    print("  i10: number;")
    print("  i14: number;")
    print("  f28: number;")
    print("  f2c: number;")
    print("  f30: number;")
    print("  f34: number;")
    print("  f38: number;")
    print("  f3c: number;")
    print("  f40: number;")
    print("}")
    print("")
    print("/** Slot k (byte offset 4k of the table 0x009ab820) lists, in order. */")
    print("export const GALGRYPHON_SCRIPT_SLOTS: readonly (readonly GalgryphonScriptRecord[])[] = [")
    for k, recs in enumerate(slots):
        print(f"  // +{4 * k:02x}")
        print("  [")
        for r in recs:
            vals = ", ".join(
                f"{key}: {fmt(r[key])}"
                for key in ("op", "min", "range", "i8", "i0c", "i10", "i14", "f28", "f2c", "f30", "f34", "f38", "f3c", "f40")
            )
            print(f"    {{ {vals} }},")
        print("  ],")
    print("];")


if __name__ == "__main__":
    main()
