import { readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { BBSession } from '../client/src/net/bbsession.ts';
import { Game } from '../client/src/net/game.ts';
import { GameItems, stackSize } from '../client/src/net/items.ts';
import { nodeBridge } from '../tests/lib/nodews.ts';
const ROOT = resolve(import.meta.dirname, '..');
const nsk = new Uint8Array(readFileSync(join(ROOT, 'vendor/newserv/system/blueburst/keys/default.nsk')));
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
async function enter(user: string) {
  const session = new BBSession({ nsk, connect: nodeBridge });
  await session.login(user, user);
  await session.characterPreviews();
  const lobby = await session.enterLobby(user, user, 0);
  return { session, lobby };
}
const a = await enter('webitema');
const b = await enter('webitemb');
const ctx = (s: BBSession) => ({ guildCardNumber: s.init!.guildCardNumber, fullCharacter: () => s.fullCharacter });
const ga = await Game.create(a.lobby, ctx(a.session), { name: 'repair', difficulty: 0, episode: 1 });
const ia = new GameItems(ga, { character: () => a.session.character, fullCharacter: () => a.session.fullCharacter });
ga.finishLoading(0, 0, 0, 0);
await ga.ready;
const entry = (await Game.list(b.lobby.conn)).find((g) => g.name === 'repair')!;
const gb = await Game.join(b.lobby, ctx(b.session), entry.itemId);
const ib = new GameItems(gb, { character: () => b.session.character, fullCharacter: () => b.session.fullCharacter });
await sleep(800);
gb.finishLoading(0, 0, 0, 0);
ib.ensureIds();
ga.sendStop(10, 0, 10, 0);
gb.sendStop(10, 0, 10, 0);
await sleep(300);
const mates = b.session.character!.inventory.find((i) => i.data.data1[0] === 3 && i.data.data1[1] === 0)!;
console.log('B monomates', stackSize(mates.data), 'A items', a.session.character!.inventory.length);
ib.drop(mates.data.id, 4);
await sleep(500);
for (const f of [...ia.floorItems.values()]) ia.pickUp(f);
await sleep(500);
console.log('A inv', a.session.character!.inventory.map((i) => [...i.data.data1.slice(0, 6)].join(',')));
await gb.leave();
await ga.leave();
a.session.close();
b.session.close();
process.exit(0);
